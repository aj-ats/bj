import { parseAbi } from 'viem';

export const rpsAbi = parseAbi([
  'function token() view returns (address)',
  'function paused() view returns (bool)',
  'function nextMatchId() view returns (uint256)',
  'function claimable(address account) view returns (uint256)',
  'function MIN_STAKE() view returns (uint256)',
  'function JOIN_WINDOW() view returns (uint256)',
  'function REVEAL_WINDOW() view returns (uint256)',
  'function matches(uint256 id) view returns (address p1, address p2, uint256 stake, bytes32 commit1, bytes32 commit2, uint8 choice1, uint8 choice2, uint64 createdAt, uint64 revealDeadline, uint8 status)',
  'function createMatch(bytes32 commit, uint256 stake) returns (uint256)',
  'function joinMatch(uint256 id, bytes32 commit)',
  'function cancel(uint256 id)',
  'function reveal(uint256 id, uint8 choice, bytes32 salt)',
  'function settle(uint256 id)',
  'function timeout(uint256 id)',
  'function claim()',
  'event Created(uint256 indexed matchId, address indexed p1, uint256 stake, bytes32 commit)',
  'event Joined(uint256 indexed matchId, address indexed p2, bytes32 commit, uint64 revealDeadline)',
  'error GameIsPaused()',
  'error BadCommit()',
  'error BadStake()',
  'error BadStatus()',
  'error BadChoice()',
  'error BadReveal()',
  'error AlreadyRevealed()',
  'error SamePlayer()',
  'error NotPlayer()',
  'error Expired()',
  'error TooEarly()',
  'error NothingToClaim()',
  'error TransferFailed()',
  'error InsufficientBalance()',
  'error InsufficientAllowance()',
]);

export const usdcAbi = parseAbi([
  'function decimals() view returns (uint8)',
  'function balanceOf(address account) view returns (uint256)',
  'function allowance(address owner, address spender) view returns (uint256)',
  'function approve(address spender, uint256 amount) returns (bool)',
  'function mint(address to, uint256 amount)',
  'error InsufficientBalance()',
  'error InsufficientAllowance()',
]);
